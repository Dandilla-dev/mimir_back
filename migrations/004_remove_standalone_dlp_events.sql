-- =============================================================================
-- Mimir — миграция 004: удаление DLP-событий standalone-аккаунтов.
--
-- Решения Р4/Р5 (mimir_account_linkage_v1.md §2, mimir_e2ee_dlp_model_v1.md
-- §3): DLP-данные о человеке, который просто пользуется мессенджером, не
-- собираются; переписку standalone-аккаунтов (без одобренного членства в
-- организации) сервер не проверяет. Код с этого момента пишет в
-- dlp_event_records события только org-linked субъектов
-- (core/message_bridge.check_incoming(), аудит Б7). Эта миграция удаляет
-- то, что успело накопиться по старому правилу «входящее проверяется
-- всегда».
--
-- КРИТЕРИЙ: у субъекта записи (subject_user_id) СЕЙЧАС нет одобренного
-- членства ни в одной организации. Снимка организации на момент записи в
-- таблице нет; на прототипе отбор по текущему членству принят как
-- допустимый (mimir_db_migration_contract.md, дополнение 2026-10-07).
-- Сейчас выйти из организации или быть исключённым нельзя (в org_store нет
-- таких операций), поэтому «сейчас без членства» = «никогда не был
-- сотрудником». Известная неточность: записи человека, который писал как
-- standalone и позже вступил в организацию, остаются.
--
-- ЗАВИСИМОСТИ (проверены по 001–003):
--   * на dlp_event_records.record_id не ссылается ни одна таблица —
--     moderation_holds, moderation_decisions, isolation_triggers ссылаются
--     на messages.message_id, не на записи событий. Каскадов нет.
--   * триггеров «только добавление» на dlp_event_records нет.
--   * представление dlp_dataset только читает таблицу; удалённые строки
--     просто пропадают из него. Метку (label) имеют только события с
--     удержанием или снятой изоляцией — а они бывают только у org-linked,
--     поэтому размеченные строки датасета не затрагиваются.
--   * сообщения, удержания, изоляции и журналы решений не трогаются.
--
-- Необратимо. На базе с реальными данными — сначала резервная копия
-- (pg_dump -t dlp_event_records) и подсчёт:
--   SELECT count(*) FROM dlp_event_records e
--   WHERE NOT EXISTS (SELECT 1 FROM memberships m
--                     WHERE m.user_id = e.subject_user_id
--                       AND m.status = 'approved');
-- =============================================================================

DELETE FROM dlp_event_records e
WHERE NOT EXISTS (
    SELECT 1
    FROM memberships m
    WHERE m.user_id = e.subject_user_id
      AND m.status  = 'approved'
);
